/* File import pipeline: CSV directly, XLS/XLSX via SheetJS (loaded on first use only).
 * Each file (or each Excel sheet) is parsed, type-detected, converted and added to the store. */
(function (root) {
  'use strict';
  const NRP = root.NRP;
  const SHEETJS = 'https://cdn.sheetjs.com/xlsx-0.20.3/package/dist/xlsx.full.min.js';
  let sheetjs = null;

  function loadSheetJS() {
    if (root.XLSX) return Promise.resolve(root.XLSX);
    if (sheetjs) return sheetjs;
    sheetjs = new Promise((resolve, reject) => {
      const s = document.createElement('script');
      s.src = SHEETJS; s.async = true;
      s.onload = () => (root.XLSX ? resolve(root.XLSX) : reject(new Error('SheetJS loaded but XLSX is missing.')));
      s.onerror = () => { sheetjs = null; reject(new Error('Could not load the Excel reader (network blocked?). Save the sheet as CSV and import that instead.')); };
      document.head.appendChild(s);
    });
    return sheetjs;
  }

  /** Convert one CSV text. Returns {kind, label, data, warnings}. */
  function convertText(text, fileName, opts = {}) {
    const hint = cells => NRP.normalize.detect(cells.map(c => String(c).trim())) !== null;
    const parsed = NRP.csv.parse(text, hint);
    const titleLine = parsed.skipped > 0 ? NRP.csv.parseRows(text)[0].join(' ') : null;
    return NRP.normalize.convert({ headers: parsed.headers, rows: parsed.rows, fileName, titleLine, indexName: opts.indexName || null });
  }

  /** Import a list of File objects. Returns [{file, ok, source?, error?}]. */
  async function importFiles(files, opts = {}) {
    const out = [];
    for (const f of files) {
      try {
        if (f.size > 60 * 1024 * 1024) throw new Error('File is larger than 60 MB.');
        const texts = [];
        if (/\.(xlsx|xls|xlsm|ods)$/i.test(f.name)) {
          const XLSX = await loadSheetJS();
          const wb = XLSX.read(await f.arrayBuffer(), { type: 'array', cellDates: false });
          wb.SheetNames.forEach(n => texts.push({ name: `${f.name} [${n}]`, text: XLSX.utils.sheet_to_csv(wb.Sheets[n], { blankrows: false }) }));
        } else if (/\.(csv|txt)$/i.test(f.name) || f.type === 'text/csv') {
          texts.push({ name: f.name, text: await f.text() });
        } else throw new Error('Unsupported file type. Use .csv, .xlsx or .xls.');
        let any = false;
        for (const t of texts) {
          try {
            const res = convertText(t.text, t.name, opts);
            const src = NRP.store.add(res, { mode: 'UPLOADED', file: t.name, origin: 'Imported by user' }, true);
            out.push({ file: t.name, ok: true, source: src }); any = true;
          } catch (e) { if (texts.length === 1) throw e; out.push({ file: t.name, ok: false, error: e.message }); }
        }
        if (!any && texts.length > 1) out.push({ file: f.name, ok: false, error: 'No sheet matched a supported layout.' });
      } catch (e) { out.push({ file: f.name, ok: false, error: e.message }); }
    }
    return out;
  }

  /** Load files bundled in js/data/bundled.js (generated by tools/bundle-data.js). */
  function loadBundled() {
    const list = root.NRP.BUNDLED || [];
    for (const b of list) {
      try {
        const res = convertText(b.text, b.file);
        NRP.store.add(res, { mode: 'HISTORICAL', file: b.file, origin: b.origin, loadedAt: b.generated }, false);
      } catch (e) { console.error('Bundled file failed:', b.file, e); }
    }
    return list.length;
  }

  NRP.importer = { importFiles, convertText, loadBundled };
})(typeof self !== 'undefined' ? self : this);
